-- 1. Supported currencies
CREATE TABLE currencies (
                            code VARCHAR(3) PRIMARY KEY,
                            name VARCHAR(50) NOT NULL
);

-- 2. Users
CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username VARCHAR(50) NOT NULL,
                       email VARCHAR(254) NOT NULL,
                       password_hash VARCHAR(255) NOT NULL,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_users_username_lower
    ON users (LOWER(username));

CREATE UNIQUE INDEX uk_users_email_lower
    ON users (LOWER(email));

-- 3. Accounts (money sources)
CREATE TABLE accounts (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          user_id BIGINT NOT NULL REFERENCES users(id),
                          name VARCHAR(100) NOT NULL,
                          currency_code VARCHAR(3) NOT NULL REFERENCES currencies(code),
                          balance NUMERIC(19, 4) NOT NULL DEFAULT 0,
                          tracking_started_at DATE NOT NULL DEFAULT CURRENT_DATE,
                          is_archived BOOLEAN NOT NULL DEFAULT FALSE,
                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT uk_accounts_id_user UNIQUE (id, user_id)
);

CREATE INDEX idx_accounts_user_id ON accounts(user_id);

-- 4. Categories
-- user_id IS NULL means a shared system category
CREATE TABLE categories (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            user_id BIGINT REFERENCES users(id),
                            name VARCHAR(100) NOT NULL,
                            type VARCHAR(10) NOT NULL,
                            is_archived BOOLEAN NOT NULL DEFAULT FALSE,
                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                            CONSTRAINT chk_categories_type
                                CHECK (type IN ('INCOME', 'EXPENSE'))
);

CREATE INDEX idx_categories_user_id ON categories(user_id);

-- 5. Transactions
CREATE TABLE transactions (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              user_id BIGINT NOT NULL REFERENCES users(id),

                              account_id BIGINT,
                              from_account_id BIGINT,
                              to_account_id BIGINT,

                              category_id BIGINT REFERENCES categories(id),
                              type VARCHAR(10) NOT NULL,
                              amount NUMERIC(19, 4) NOT NULL,
                              description TEXT,
                              occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                              deleted_at TIMESTAMPTZ,
                              created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                              CONSTRAINT chk_transactions_type
                                  CHECK (type IN ('INCOME', 'EXPENSE', 'TRANSFER')),

                              CONSTRAINT chk_transactions_amount
                                  CHECK (amount > 0),

                              CONSTRAINT fk_transactions_account_user
                                  FOREIGN KEY (account_id, user_id)
                                      REFERENCES accounts(id, user_id),

                              CONSTRAINT fk_transactions_from_account_user
                                  FOREIGN KEY (from_account_id, user_id)
                                      REFERENCES accounts(id, user_id),

                              CONSTRAINT fk_transactions_to_account_user
                                  FOREIGN KEY (to_account_id, user_id)
                                      REFERENCES accounts(id, user_id),

                              CONSTRAINT chk_transactions_accounts
                                  CHECK (
                                      (
                                          type IN ('INCOME', 'EXPENSE')
                                              AND account_id IS NOT NULL
                                              AND from_account_id IS NULL
                                              AND to_account_id IS NULL
                                          )
                                          OR
                                      (
                                          type = 'TRANSFER'
                                              AND account_id IS NULL
                                              AND category_id IS NULL
                                              AND from_account_id IS NOT NULL
                                              AND to_account_id IS NOT NULL
                                              AND from_account_id <> to_account_id
                                          )
                                      )
);

CREATE INDEX idx_transactions_user_occurred
    ON transactions(user_id, occurred_at DESC);

CREATE INDEX idx_transactions_account
    ON transactions(account_id);

CREATE INDEX idx_transactions_from_account
    ON transactions(from_account_id);

CREATE INDEX idx_transactions_to_account
    ON transactions(to_account_id);

CREATE INDEX idx_transactions_category
    ON transactions(category_id);

-- 6. Monthly budgets
CREATE TABLE budgets (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         user_id BIGINT NOT NULL REFERENCES users(id),
                         category_id BIGINT NOT NULL REFERENCES categories(id),
                         currency_code VARCHAR(3) NOT NULL REFERENCES currencies(code),
                         budget_month DATE NOT NULL,
                         amount_limit NUMERIC(19, 4) NOT NULL,
                         created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                         CONSTRAINT chk_budgets_amount
                             CHECK (amount_limit > 0),

                         CONSTRAINT chk_budgets_month
                             CHECK (EXTRACT(DAY FROM budget_month) = 1),

                         CONSTRAINT uk_budgets_user_category_currency_month
                             UNIQUE (user_id, category_id, currency_code, budget_month)
);

CREATE INDEX idx_budgets_user_month
    ON budgets(user_id, budget_month);

